#!/usr/bin/env bash
# Build the IPv6 scan-probe oracle (IPv6 scans step c). The builders it calls are
# nmap's own, copied out by name at build time into scanprobe6_c.inc (gitignored):
#
#   tcpip.cc        ipv6_cksum, build_ipv6_raw, build_tcp, build_tcp_raw_ipv6,
#                   build_udp, build_udp_raw_ipv6
#   netutil.cc      ipv6_pseudoheader_cksum
#   ip-util.c       ip_cksum_add (libdnet; ip_cksum_carry is dnet/ip.h's macro)
#   scan_engine_raw.cc  seq32_encode, sport_encode
#
# compiled against libdnet's own headers, with o.badsum, safe_malloc and the random
# hooks the probe paths never reach supplied by scanprobe6_oracle.cc. What the
# oracle transcribes (with line references) is only how sendIPScanProbe chooses
# their arguments. Each copy must be found exactly as named or the build fails, so
# a change in nmap's source stops the oracle instead of testing a stale copy.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
NROOT="$(cd "$HERE/../../../../.." && pwd)"   # repo root (nmap/)
INC="$HERE/scanprobe6_c.inc"

# Print one top-level function: from its definition line (exact text) to the
# first closing brace in column 0. With `kr`, also the line before it, for a
# definition that puts its return type on a line of its own.
extract() {
  local file="$1" head="$2" kr="${3:-}"
  awk -v head="$head" -v kr="$kr" '
    !on && $0 == head { on = 1; if (kr != "") print prev }
    on { print }
    on && /^}/ { found = 1; exit }
    { prev = $0 }
    END { if (!found) exit 1 }
  ' "$file" || { echo "error: '$head' not found in $file" >&2; exit 1; }
}

{
  echo "// Generated by build_scanprobe6_oracle.sh from nmap's sources. Do not edit."
  extract "$NROOT/libdnet-stripped/src/ip-util.c" 'ip_cksum_add(const void *buf, size_t len, int cksum)' kr
  extract "$NROOT/libnetutil/netutil.cc" 'u16 ipv6_pseudoheader_cksum(const struct in6_addr *src,'
  extract "$NROOT/tcpip.cc" 'static u16 ipv6_cksum(const struct in6_addr *src, const struct in6_addr *dst,'
  extract "$NROOT/tcpip.cc" 'u8 *build_ipv6_raw(const struct in6_addr *source,'
  extract "$NROOT/tcpip.cc" 'static u8 *build_tcp(u16 sport, u16 dport, u32 seq, u32 ack, u8 reserved,'
  extract "$NROOT/tcpip.cc" 'u8 *build_tcp_raw_ipv6(const struct in6_addr *source,'
  extract "$NROOT/tcpip.cc" 'static u8 *build_udp(u16 sport, u16 dport, const char *data, u16 datalen,'
  extract "$NROOT/tcpip.cc" 'u8 *build_udp_raw_ipv6(const struct in6_addr *source,'
  extract "$NROOT/scan_engine_raw.cc" 'static u32 seq32_encode(UltraScanInfo *USI, tryno_t trynum) {'
  extract "$NROOT/scan_engine_raw.cc" 'static u16 sport_encode(u16 base_portno, tryno_t trynum) {'
} > "$INC"

CXX="${CXX:-g++}"
$CXX -O2 -Wall -Wno-unused-function -I"$HERE" -I"$NROOT/libdnet-stripped/include" \
  "$HERE/scanprobe6_oracle.cc" -o "$HERE/scanprobe6_oracle"
echo "built $HERE/scanprobe6_oracle"
