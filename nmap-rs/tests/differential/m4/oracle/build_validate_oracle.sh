#!/usr/bin/env bash
# Build the receive-validation oracle: a transcription of tcpip.cc's static
# validatepkt()/validateTCPhdr() (see validate_oracle.cc for the line map), with
# the IPv6 extension-header walk taken verbatim from libnetutil/netutil.cc.
#
# The walk functions are static in netutil.cc and netutil.cc cannot be linked
# without libpcap and libdnet, so they are copied out by name into
# validate_ipv6_walk.inc (gitignored) and compiled against libdnet's own headers.
# Each copy must be found exactly as named, or the build fails: a rename or
# signature change in netutil.cc stops the oracle instead of silently testing a
# stale copy.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
NROOT="$(cd "$HERE/../../../../.." && pwd)"   # repo root (nmap/)
NETUTIL="$NROOT/libnetutil/netutil.cc"
INC="$HERE/validate_ipv6_walk.inc"

# Print one top-level function of netutil.cc: from its definition line (the
# exact text, with no trailing `;`, so the forward declarations do not match) to
# the first closing brace in column 0.
extract() {
  awk -v head="$1" '
    !on && $0 == head { on = 1 }
    on { print }
    on && /^}/ { found = 1; exit }
    END { if (!found) exit 1 }
  ' "$NETUTIL" || { echo "error: '$1' not found in $NETUTIL" >&2; exit 1; }
}

{
  echo "// Generated by build_validate_oracle.sh from libnetutil/netutil.cc. Do not edit."
  extract 'static int ipv6_is_extension_header(u8 type)'
  extract 'static int ipv6_is_upperlayer(u8 type)'
  extract 'static const u8 *ipv6_get_data_primitive(const struct ip6_hdr *ip6, const u8 *packet,'
  extract 'static const u8 *ipv6_get_data(const struct ip6_hdr *ip6, const u8 *p, unsigned int *len, u8 *nxt)'
  extract 'const u8 *ipv6_get_data(const u8 *p, unsigned int *len, u8 *nxt)'
} > "$INC"

CXX="${CXX:-g++}"
$CXX -O2 -Wall -I"$HERE" -I"$NROOT/libdnet-stripped/include" \
  "$HERE/validate_oracle.cc" -o "$HERE/validate_oracle"
echo "built $HERE/validate_oracle"
