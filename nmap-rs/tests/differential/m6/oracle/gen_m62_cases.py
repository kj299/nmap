"""Generate the M6.2 differential corpus: the `--script` selection grammar.

The oracle is nmap's own Lua 5.4.8 AND nmap's own LPeg, both compiled from this
repository by `build_lua_oracle.sh`, running the selection grammar sliced
verbatim out of `nse_main.lua` and `nselib/lpeg-utility.lua` by
`extract_nse_main.py`. Nothing about how a `--script` expression is parsed or
evaluated is restated here.

That matters more for M6.2 than it did for M6.1. The grammar's observable
behaviour is a property of LPeg specifically — ordered choice, possessive
repetition that never gives characters back, capture functions that run only
after the whole match succeeds, and a backtrack stack that gives out at a
startlingly shallow nesting depth. A hand-written oracle would encode what a
PEG "should" do and quietly bless the same wrong answers as the port.

Only the CASES below are ours: inputs chosen to pin the corners.
"""

import hashlib
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import extract_nse_main as ex  # noqa: E402

# The blocks this generator pastes, in dependency order.
M62_BLOCKS = [
    "caselessp",
    "caseless",
    "keyword",
    "grammar",
    "globs",
    "entry_match",
    "rule_normalise",
]


def build_driver(root):
    """Emit the Lua oracle driver, with the grammar pasted in verbatim."""
    blocks = ex.extract(root)
    missing = [n for n in M62_BLOCKS if n not in blocks]
    if missing:
        raise ex.ExtractError(f"missing blocks: {missing}")
    digest = ex.provenance(blocks)

    def text(name):
        return blocks[name][0]

    def where(name):
        _, first, last = blocks[name]
        src = ex.LPEG_UTILITY if name in ex.LPEG_UTILITY_BLOCKS else ex.NSE_MAIN
        return f"{src}:{first}-{last}"

    parts = [
        "-- GENERATED by oracle/gen_m62_cases.py. Do not edit.\n",
        "--\n",
        "-- Every block below marked VERBATIM is pasted byte for byte out of the\n",
        "-- nmap sources named beside it. Provenance digest over all extracted\n",
        f"-- blocks: {digest}\n",
        "--\n",
        "-- This driver is the M6.2 oracle: nmap's own Lua running nmap's own LPeg\n",
        "-- over nmap's own selection grammar.\n\n",
        'local lpeg = require "lpeg"\n',
        "local locale, P, R, S, V, Cc = lpeg.locale, lpeg.P, lpeg.R, lpeg.S, lpeg.V, lpeg.Cc\n",
        "local match, gsub, find = string.match, string.gsub, string.find\n",
        "local lower, upper = string.lower, string.upper\n",
        "local assert, ipairs, pcall, setmetatable = assert, ipairs, pcall, setmetatable\n",
        "local tostring, tonumber, type = tostring, tonumber, type\n\n",
        # `caseless` lives in lpeg-utility, which pulls in stdnse -> the `nmap`
        # module, which only exists inside a running nmap process. Rather than
        # stub `nmap` (and risk the stub deciding the answer), the two functions
        # the grammar actually uses are lifted verbatim and bound to `U` here.
        f"-- VERBATIM {where('caselessp')}\n",
        text("caselessp") + "\n\n",
        f"-- VERBATIM {where('caseless')}\n",
        text("caseless") + "\n\n",
        "local U = { caseless = caseless }\n\n",
        f"-- VERBATIM {where('keyword')}\n",
        text("keyword") + "\n\n",
    ]

    # The grammar and glob blocks are indented as they appear inside
    # `get_chosen_scripts`; pasting them at file scope is legal Lua and keeps
    # them byte-identical, which is the property that matters.
    parts += [
        f"-- VERBATIM {where('grammar')}\n",
        text("grammar") + "\n\n",
        f"-- VERBATIM {where('globs')}\n",
        text("globs") + "\n\n",
    ]

    # Per-case evaluation: bind `filename` and `categories`, paste the entry
    # wiring, run the rule.
    parts.append(
        """
-- Evaluate one rule against one script entry, exactly as
-- `script_database.Entry` does.
local function evaluate (rule, filename, categories)
"""
    )
    parts.append(f"  -- VERBATIM {where('entry_match')}\n")
    parts.append(text("entry_match") + "\n")
    parts.append(
        """
  local ok, res = pcall(function () return T:match(rule) end)
  if not ok then
    local msg = tostring(res)
    if find(msg, "too many pending calls/choices", 1, true) then
      return "ERROR:backtrack"
    end
    return "ERROR:other"
  end
  if res == nil then
    return "REJECT"                      -- not an expression at all
  end
  return ("ACCEPT:%s:%s"):format(tostring(not not res), tostring(selected_by_name))
end

-- Normalise one rule the way `get_chosen_scripts` does before matching:
-- strip surrounding whitespace and peel a leading "+" (forced).
local function normalise (raw)
  local rules = { raw }
  local used_rules, forced_rules = {}, {}
"""
    )
    parts.append(f"  -- VERBATIM {where('rule_normalise')}\n")
    parts.append(text("rule_normalise") + "\n")
    parts.append(
        """
  local out = rules[1]
  -- A rule that is empty after stripping is never entered into used_rules, and
  -- rules[i] keeps its ORIGINAL text.
  if used_rules[out] == nil then
    return "SKIP:" .. out
  end
  return ("RULE:%s:%s"):format(tostring(not not forced_rules[out]), out)
end

local function unhex (s)
  return (s:gsub("%x%x", function (b) return string.char(tonumber(b, 16)) end))
end

-- stdin: one case per line.
--   match<TAB>rule_hex<TAB>basename_hex<TAB>cat_hex,cat_hex,...
--   norm<TAB>rule_hex
for line in io.lines() do
  local kind, rest = line:match("^(%w+)\\t(.*)$")
  if kind == "match" then
    local rule_hex, base_hex, cats_hex = rest:match("^(%x*)\\t(%x*)\\t(.*)$")
    local cats = {}
    for c in cats_hex:gmatch("[^,]+") do cats[#cats+1] = unhex(c) end
    io.write(evaluate(unhex(rule_hex), unhex(base_hex), cats), "\\n")
  elseif kind == "norm" then
    io.write(normalise(unhex(rest)), "\\n")
  else
    error("bad case kind: " .. tostring(kind))
  end
end
"""
    )
    return "".join(parts), digest


