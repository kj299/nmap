#: Cases where this port deliberately parts company with the C. Keyed by case
#: name -> (expected_verdict, why). Every entry is ledgered in DIVERGENCES.md
#: and pinned by name in `crates/core/tests/selection_differential.rs`.
DIVERGENCES = {
    # The C's ceiling is an LPeg backtrack-stack artifact (MAXBACK = 100,
    # divided by the per-level cost of this grammar), not a designed limit.
    # This port accepts every rule the C accepts and keeps going further.
    "nesting_15": ("ACCEPT:true:false", "the C's stack gives out at 15 nested parens"),
    "nesting_16": ("ACCEPT:true:false", "the C's stack gives out at 15 nested parens"),
    "nesting_40": ("ACCEPT:true:false", "the C's stack gives out at 15 nested parens"),
    "and_chain_19": ("ACCEPT:true:false", "the C's stack gives out at 19 `and`s"),
    "and_chain_25": ("ACCEPT:true:false", "the C's stack gives out at 19 `and`s"),
    "or_chain_31": ("ACCEPT:true:false", "the C's stack gives out at 31 `or`s"),
    "or_chain_40": ("ACCEPT:true:false", "the C's stack gives out at 31 `or`s"),
}

HEADER_CASES = (
    "# name\trule_hex\tfilename_hex\tcategories_hex\tnote\n"
    "# Generated by oracle/gen_m62_cases.py. Do not edit by hand.\n"
)
HEADER_NORM = (
    "# name\trule_hex\tnote\n"
    "# Generated by oracle/gen_m62_cases.py. Do not edit by hand.\n"
)
HEADER_GOLDEN = (
    "# name\toracle\texpected\n"
    "# `oracle` is the verdict of nmap's OWN Lua 5.4 and OWN LPeg, built from\n"
    "# liblua/ + lpeg.c, running the selection grammar sliced verbatim out of\n"
    "# nse_main.lua and nselib/lpeg-utility.lua.\n"
    "# A row whose two columns disagree is a deliberate divergence, ledgered in\n"
    "# DIVERGENCES.md and pinned by name in the differential test.\n"
)


def run_oracle(driver_path, stdin_text, lua):
    proc = subprocess.run(
        [lua, driver_path],
        input=stdin_text,
        capture_output=True,
        text=True,
    )
    if proc.returncode != 0:
        raise RuntimeError(f"oracle failed: {proc.stderr.strip()[:400]}")
    return proc.stdout.rstrip("\n").split("\n")


def emit(out_dir, driver_path, lua):
    match_stdin = "".join(
        "match\t{}\t{}\t{}\n".format(
            rule.encode("latin-1").hex(),
            base.encode("latin-1").hex(),
            ",".join(c.encode("latin-1").hex() for c in cats),
        )
        for _n, rule, base, cats, _note in MATCH_CASES
    )
    norm_stdin = "".join(
        "norm\t{}\n".format(rule.encode("latin-1").hex())
        for _n, rule, _note in NORM_CASES
    )

    match_out = run_oracle(driver_path, match_stdin, lua)
    norm_out = run_oracle(driver_path, norm_stdin, lua)
    if len(match_out) != len(MATCH_CASES):
        raise RuntimeError(f"oracle returned {len(match_out)} rows for {len(MATCH_CASES)} cases")
    if len(norm_out) != len(NORM_CASES):
        raise RuntimeError(f"oracle returned {len(norm_out)} rows for {len(NORM_CASES)} cases")

    cases, golden = [], []
    for (name, rule, base, cats, note), verdict in zip(MATCH_CASES, match_out):
        cases.append(
            "{}\t{}\t{}\t{}\t{}".format(
                name,
                rule.encode("latin-1").hex(),
                base.encode("latin-1").hex(),
                ",".join(c.encode("latin-1").hex() for c in cats),
                note,
            )
        )
        expected = DIVERGENCES.get(name, (verdict, None))[0]
        golden.append(f"{name}\t{verdict}\t{expected}")

    norms, norm_golden = [], []
    for (name, rule, note), verdict in zip(NORM_CASES, norm_out):
        norms.append("{}\t{}\t{}".format(name, rule.encode("latin-1").hex(), note))
        norm_golden.append(f"{name}\t{verdict}\t{verdict}")

    files = {
        "m62_cases.txt": HEADER_CASES + "\n".join(cases) + "\n",
        "m62_golden.txt": HEADER_GOLDEN + "\n".join(golden) + "\n",
        "m62_norm_cases.txt": HEADER_NORM + "\n".join(norms) + "\n",
        "m62_norm_golden.txt": HEADER_GOLDEN + "\n".join(norm_golden) + "\n",
    }
    files["m62_fixtures.rs"] = fixtures(cases, golden, norms, norm_golden)
    for name, body in files.items():
        with open(os.path.join(out_dir, name), "w", encoding="utf-8") as fh:
            fh.write(body)
    return len(MATCH_CASES), len(NORM_CASES)


def fixtures(cases, golden, norms, norm_golden):
    """The same inputs as Rust consts, for the Miri-visible unit tests."""

    def lit(hexstr):
        raw = bytes.fromhex(hexstr)
        return "&[" + ", ".join(str(b) for b in raw) + "]"

    out = [
        "// GENERATED by tests/differential/m6/oracle/gen_m62_cases.py. Do not edit.\n",
        "//\n",
        "// The same inputs as the M6.2 differential corpus, as Rust consts, so the\n",
        "// unit tests in `core::nse::selection` can exercise them under Miri — where\n",
        "// there is no filesystem to read the corpus from. `regen_m62.sh --check`\n",
        "// re-derives this file, which is what stops the Miri-visible tests from\n",
        "// drifting away from the oracle.\n\n",
        "/// One corpus row: the case name, the rule, the index entry's filename,\n",
        "/// its categories, and the verdict this port must reach. `expected` is\n",
        "/// `ACCEPT:<matched>:<by_name>`, `REJECT`, or `ERROR:<class>`, exactly as\n",
        "/// the golden file records it.\n",
        "pub type SelectionCase = (\n",
        "    &'static str,\n",
        "    &'static [u8],\n",
        "    &'static [u8],\n",
        "    &'static [&'static [u8]],\n",
        "    &'static str,\n",
        ");\n\n",
        "/// Every case in the M6.2 differential corpus.\n",
        "pub const SELECTION_CASES: &[SelectionCase] = &[\n",
    ]
    expected = {row.split("\t")[0]: row.split("\t")[2] for row in golden}
    for row in cases:
        name, rule_hex, base_hex, cats_hex, _note = row.split("\t")
        cats = "&[" + ", ".join(lit(c) for c in cats_hex.split(",") if c) + "]"
        out.append(
            f'    ("{name}", {lit(rule_hex)}, {lit(base_hex)}, {cats}, "{expected[name]}"),\n'
        )
    out.append("];\n\n")
    out += [
        "/// `(name, raw_rule, expected)` for rule normalisation. `expected` is\n",
        "/// `RULE:<forced>:<text>` or `SKIP:<original>`.\n",
        "pub const NORM_CASES: &[(&str, &[u8], &str)] = &[\n",
    ]
    nexpected = {row.split("\t")[0]: row.split("\t")[2] for row in norm_golden}
    for row in norms:
        name, rule_hex, _note = row.split("\t")
        out.append(f'    ("{name}", {lit(rule_hex)}, "{nexpected[name]}"),\n')
    out.append("];\n")
    return "".join(out)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.abspath(os.path.join(here, "..", "..", "..", "..", ".."))
    # An explicit output directory lets regen_m62.sh generate into a scratch
    # dir and diff, so --check never touches the committed files.
    out_dir = sys.argv[1] if len(sys.argv) > 1 else os.path.abspath(os.path.join(here, ".."))
    lua = os.path.join(here, "lua")

    driver, digest = build_driver(root)
    driver_path = os.path.join(here, "m62_driver.lua")
    with open(driver_path, "w", encoding="utf-8") as fh:
        fh.write(driver)

    n_match, n_norm = emit(out_dir, driver_path, lua)
