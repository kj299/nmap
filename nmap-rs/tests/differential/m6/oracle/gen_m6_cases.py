# ---------------------------------------------------------------------------
# Running the oracle and emitting the corpus
# ---------------------------------------------------------------------------

HEADER_CASES = "# name\t{}_hex\tnote\n# Generated by oracle/gen_m6_cases.py. Do not edit by hand.\n"
HEADER_GOLDEN = (
    "# name\toracle\texpected\n"
    "# `oracle` is the verdict of nmap's OWN Lua 5.4, built from liblua/ and\n"
    "# running loading logic sliced verbatim out of nse_main.lua.\n"
    "# A row whose two columns disagree is a deliberate divergence, ledgered in\n"
    "# DIVERGENCES.md: the C accepts it and this port refuses it, on purpose.\n"
)


def run_oracle(driver, mode, payload, work):
    """Feed one case to the Lua oracle; return its verdict line."""
    path = os.path.join(work, "case.nse" if mode == "nse" else "case.db")
    with open(path, "wb") as fh:
        fh.write(payload)
    proc = subprocess.run(
        [LUA, driver, mode, path],
        capture_output=True, text=True, timeout=60, cwd=work,
    )
    out = proc.stdout.strip()
    if not out.startswith("LUA_"):
        raise RuntimeError(f"oracle produced no verdict: {proc.stdout!r} {proc.stderr!r}")
    return out


def expected_for(name, oracle, divergences):
    """What this port must do: mirror Lua, except where we refuse on purpose."""
    if name in divergences:
        return "REJECT"
    return "ACCEPT:" + oracle[len("LUA_OK:"):] if oracle.startswith("LUA_OK:") else "REJECT"


def emit(out_dir, work, driver_path):
    written = []
    for kind, cases, divergences, mode in (
        ("scriptdb", DB_CASES, DB_DIVERGENCES, "db"),
        ("nse", NSE_CASES, NSE_DIVERGENCES, "nse"),
    ):
        rows, golden = [], []
        for name, text, note in cases:
            payload = text.encode("utf-8")
            oracle = run_oracle(driver_path, mode, payload, work)
            rows.append(f"{name}\t{payload.hex()}\t{note}")
            golden.append(f"{name}\t{oracle}\t{expected_for(name, oracle, divergences)}")
        cp = os.path.join(out_dir, f"m6_{kind}_cases.txt")
        gp = os.path.join(out_dir, f"m6_{kind}_golden.txt")
        with open(cp, "w", encoding="utf-8") as fh:
            fh.write(HEADER_CASES.format("db" if mode == "db" else "src"))
            fh.write("\n".join(rows) + "\n")
        with open(gp, "w", encoding="utf-8") as fh:
            fh.write(HEADER_GOLDEN)
            fh.write("\n".join(golden) + "\n")
        written += [cp, gp]
    return written


FIXTURE_HEAD = '''// GENERATED by tests/differential/m6/oracle/gen_m6_cases.py. Do not edit.
//
// The same inputs as the differential corpus, as Rust consts, so the unit tests
// in `core::nse::script` can exercise them under Miri — where there is no
// filesystem to read the corpus from. `regen_m6.sh --check` re-derives this file,
// which is what stops the Miri-visible tests from drifting away from the oracle.

/// `(name, input, expected)` for the script.db grammar. `expected` is
/// `ACCEPT:<serialized>` or `REJECT`, exactly as the golden file records it.
pub const SCRIPTDB_CASES: &[(&str, &[u8], &str)] = &[
'''


def emit_fixtures(out_dir, rows_db, rows_nse):
    def lit(b):
        return "&[" + ", ".join(str(x) for x in b) + "]"

    parts = [FIXTURE_HEAD]
    for name, payload, expected in rows_db:
        parts.append(f'    ("{name}", {lit(payload)}, "{expected}"),\n')
    parts.append("];\n\n")
    parts.append(
        "/// `(name, source, expected)` for `.nse` metadata extraction.\n"
        "pub const NSE_CASES: &[(&str, &[u8], &str)] = &[\n"
    )
    for name, payload, expected in rows_nse:
        parts.append(f'    ("{name}", {lit(payload)}, "{expected}"),\n')
    parts.append("];\n")
    path = os.path.join(out_dir, "m6_fixtures.rs")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("".join(parts))
    return path


def main():
    out_dir = sys.argv[1]
    os.makedirs(out_dir, exist_ok=True)
    work = os.path.join(out_dir, "_work")
    os.makedirs(work, exist_ok=True)

    driver_path = os.path.join(work, "nse_oracle.lua")
    with open(driver_path, "w", encoding="utf-8") as fh:
        fh.write(build_driver())

    collected = {}
    for kind, cases, divergences, mode in (
        ("scriptdb", DB_CASES, DB_DIVERGENCES, "db"),
        ("nse", NSE_CASES, NSE_DIVERGENCES, "nse"),
    ):
        rows = []
        for name, text, _note in cases:
            payload = text.encode("utf-8")
            oracle = run_oracle(driver_path, mode, payload, work)
            rows.append((name, payload, expected_for(name, oracle, divergences)))
        collected[kind] = rows

    written = emit(out_dir, work, driver_path)
    written.append(emit_fixtures(out_dir, collected["scriptdb"], collected["nse"]))
    for p in written:
        print(os.path.basename(p))


if __name__ == "__main__":
    main()
