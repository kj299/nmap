#!/usr/bin/env python3
"""Generate the M6.1 differential corpus and its golden verdicts.

The oracle is nmap's OWN Lua 5.4 interpreter, built from `liblua/` in this
repository, running loading logic sliced verbatim out of `nse_main.lua` (see
`extract_nse_main.py`). Nothing about how nmap reads `script.db` or extracts
`.nse` metadata is re-stated here; it is pasted in.

Emits, into the directory given as argv[1]:
    m6_scriptdb_cases.txt    the script.db corpus       (name, hex, note)
    m6_scriptdb_golden.txt   Lua's verdict + this port's (name, oracle, expected)
    m6_nse_cases.txt         the .nse corpus
    m6_nse_golden.txt        Lua's verdict + this port's
    m6_fixtures.rs           the same inputs as Rust consts, for the Miri-visible
                             unit tests (no filesystem under Miri)
"""

