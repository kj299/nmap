#!/usr/bin/env python3
"""M6.6 step b: screen the LPeg tree corpus for undefined behaviour in the C.

    ubsan_m66b_trees.py LUA_UBSAN CASES GOLDEN

LUA_UBSAN is the oracle built with -fsanitize=undefined -fno-sanitize-recover=all
(oracle/build_lua_oracle.sh --variant ubsan), so the first undefined operation
ends the process. Every row of CASES runs through it (oracle/m66b_tree_driver.lua,
200 rows a process, a failed batch re-run a row at a time), and:

  * a row whose note carries `[wrapv]` must stop on a signed integer overflow
    in lpeg.c: its size overflows the C's `int` (lpeg-tree-size-int-overflow),
    and its golden answer comes from the -fwrapv build, where that overflow is
    defined to wrap. A listed row that no longer overflows fails: the list is
    exact.
  * every other row must run clean, and print exactly its GOLDEN line: the
    golden, generated by the -fwrapv build, is then also what standard C gives
    on it, so -fwrapv decided nothing but the listed rows.

Any other report, crash or hang fails (LESSONS #033: a golden records no
undefined behaviour). Driven by ../regen_m66b_trees.sh, which CI runs.
"""
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
DRIVER = os.path.join(HERE, "m66b_tree_driver.lua")
CORE = os.path.join(HERE, "m66b_tree_core.lua")
BATCH = 200
REPORT = re.compile(r"(\w+\.c):(\d+):\d+: runtime error: ([^\n]{0,120})")


def rows_of(path):
    with open(path, encoding="latin-1") as fh:
        return [l if l.endswith("\n") else l + "\n" for l in fh if l.strip() and not l.startswith("#")]


def run(lua, work, rows):
    """(rc, stdout, stderr) for these rows in one process; rc None on a hang."""
    path = os.path.join(work, "chunk.txt")
    with open(path, "w", encoding="latin-1") as fh:
        fh.writelines(rows)
    env = dict(os.environ, UBSAN_OPTIONS="halt_on_error=1:print_stacktrace=0")
    try:
        p = subprocess.run([lua, DRIVER, CORE, path], capture_output=True, env=env, timeout=300)
    except subprocess.TimeoutExpired:
        return None, "", "timeout"
    return p.returncode, p.stdout.decode("latin-1"), p.stderr.decode("latin-1")


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    lua, cases, golden = sys.argv[1:]
    rows = rows_of(cases)
    gold = {l.split("\t", 1)[0]: l.rstrip("\n") for l in rows_of(golden)}
    wrapv = {r.split("\t", 1)[0] for r in rows if "[wrapv]" in r.rstrip("\n").split("\t")[-1]}
    clean, overflowed, bad = 0, {}, []

    def judge_clean(cid, line):
        nonlocal clean
        if cid in wrapv:
            bad.append("%s: listed [wrapv] but no undefined behaviour" % cid)
        elif gold.get(cid) != line:
            bad.append("%s: clean under UBSan, but not the golden's line (-fwrapv decided it)" % cid)
        else:
            clean += 1

    with tempfile.TemporaryDirectory(prefix="m66b-ubsan-") as work:
        for i in range(0, len(rows), BATCH):
            batch = rows[i:i + BATCH]
            rc, out, _ = run(lua, work, batch)
            lines = out.splitlines()
            if rc == 0 and len(lines) == len(batch):
                for r, line in zip(batch, lines):
                    judge_clean(r.split("\t", 1)[0], line)
                continue
            for r in batch:   # a row in this batch stopped the process: one at a time
                cid = r.split("\t", 1)[0]
                rc1, out1, err1 = run(lua, work, [r])
                m = REPORT.search(err1)
                if rc1 == 0:
                    judge_clean(cid, out1.rstrip("\n"))
                elif cid in wrapv and m and m.group(1) == "lpeg.c" \
                        and m.group(3).startswith("signed integer overflow"):
                    overflowed[cid] = "lpeg.c:%s" % m.group(2)
                else:
                    what = m.group(0) if m else ("rc %s: %s" % (rc1, err1.strip()[-200:]))
                    bad.append("%s: undefined behaviour or a crash in the C: %s" % (cid, what))
    sites = sorted(set(overflowed.values()), key=lambda s: int(s.split(":")[1]))
    print("m66b trees under UBSan: %d rows, %d clean and equal to the golden, %d [wrapv] rows overflow "
          "the C's int as listed (%s)" % (len(rows), clean, len(overflowed), ", ".join(sites)))
    if bad:
        for b in bad[:40]:
            sys.stderr.write("  " + b + "\n")
        sys.exit("FAIL: %d rows of m66b_tree_cases.txt are undefined in the C or not as listed "
                 "(LESSONS #033; oracle/ubsan_m66b_trees.py)" % len(bad))


if __name__ == "__main__":
    main()
